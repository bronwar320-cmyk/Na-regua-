-- NA RÉGUA BARBER SHOP: banco de dados e segurança do painel
-- Execute este arquivo no Supabase > SQL Editor.

create table if not exists public.agendamentos (
  id bigint generated by default as identity primary key,
  nome text not null,
  telefone text not null,
  email text,
  servico text not null,
  data_desejada date not null,
  horario_desejado time not null,
  status text not null default 'pendente'
    check (status in ('pendente', 'confirmado', 'recusado', 'cancelado')),
  criado_em timestamptz not null default now()
);

create table if not exists public.barber_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  criado_em timestamptz not null default now()
);

alter table public.agendamentos enable row level security;
alter table public.barber_admins enable row level security;

-- Função SECURITY DEFINER evita recursão das políticas da tabela de administradores.
create or replace function public.is_barber_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.barber_admins
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_barber_admin() from public;
grant execute on function public.is_barber_admin() to authenticated;

-- Visitantes podem apenas criar solicitações pendentes.
drop policy if exists "Public can request appointments" on public.agendamentos;
create policy "Public can request appointments"
on public.agendamentos for insert
to anon, authenticated
with check (
  status = 'pendente'
  and length(trim(nome)) between 2 and 100
  and length(trim(telefone)) between 8 and 30
  and length(trim(servico)) between 2 and 150
);

-- Somente usuários cadastrados em barber_admins podem ver e gerenciar agendamentos.
drop policy if exists "Admins can view appointments" on public.agendamentos;
create policy "Admins can view appointments"
on public.agendamentos for select
to authenticated
using (public.is_barber_admin());

drop policy if exists "Admins can update appointments" on public.agendamentos;
create policy "Admins can update appointments"
on public.agendamentos for update
to authenticated
using (public.is_barber_admin())
with check (public.is_barber_admin());

drop policy if exists "Admins can delete appointments" on public.agendamentos;
create policy "Admins can delete appointments"
on public.agendamentos for delete
to authenticated
using (public.is_barber_admin());

-- Cada usuário autenticado só pode consultar sua própria linha de admin.
drop policy if exists "Admins can view own admin record" on public.barber_admins;
create policy "Admins can view own admin record"
on public.barber_admins for select
to authenticated
using (user_id = (select auth.uid()));

